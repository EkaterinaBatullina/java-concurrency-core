package com.technokratos.blockingqueue;

import java.util.concurrent.*;
import java.util.concurrent.locks.ReentrantLock;

public class BlockingQueueTask {

    /*
     * По умолчанию используется "нечестный" (non-fair) режим блокировки.
     * Режим fairness=true намеренно не включается, так как строгое соблюдение
     * очереди потоков приводит к избыточным контекстным переключениям (context switches)
     * и падению пропускной способности из-за постоянного засыпания/пробуждения потоков.
     * (Ситуации, при которых только что пришедший runnable-поток намеренно переводится
     * в состояние waiting и паркуется в конец очереди и ожидается пробуждение наиболее
     * долго ждущего потока в начале очереди).
     * Нечестный режим позволяет новому потоку сразу захватить
     * освободившийся лок, что максимизирует утилизацию процессора.
     */
    private static final ReentrantLock logLock = new ReentrantLock();

    public static void main(String[] args) {

        /*
         * Ограниченная очередь создает backpressure:
         * если буфер заполнен, producer блокируется в вызове put()
         * и не может производить данные быстрее, чем consumer успевает
         * их извлекать.
         *
         * Внутри ArrayBlockingQueue поток ожидает на Condition notFull,
         * связанной с общим ReentrantLock. После освобождения места
         * consumer выполняет signal(), а ожидающий поток переводится
         * в очередь синхронизатора и впоследствии пробуждается через
         * механизм LockSupport.unpark().
         *
         * В примере используется ArrayBlockingQueue, которая работает
         * через один общий lock для операций put() и take().
         *
         * В отличие от неё LinkedBlockingQueue использует два отдельных
         * lock'а (putLock и takeLock), что позволяет producer и consumer
         * эффективнее выполнять операции параллельно.
         */
        BlockingQueue<Integer> queue = new ArrayBlockingQueue<>(5);

        /*
         * ExecutorService автоматически закрывается при выходе из try блока.
         *
         * Метод close() инициирует завершение пула и ожидает окончания
         * уже запущенных задач. После этого новые задачи больше не принимаются.
         *
         * Благодаря этому main-поток не завершится раньше producer и consumer,
         * а приложение дождётся обработки всех элементов очереди.
         *
         * Каждая задача запускается в собственном виртуальном потоке.
         *
         * Блокирующие операции (put(), take(), sleep()) приостанавливают
         * выполнение виртуального потока, не требуя выделения отдельного
         * платформенного потока на каждую задачу.
         *
         * Это позволяет масштабировать количество одновременно ожидающих
         * задач лучше, чем один платформенный поток на задачу.
         */
        try (ExecutorService executor = Executors.newVirtualThreadPerTaskExecutor()) {

            executor.submit(() -> {
                try {
                    for (int i = 1; i <= 10; i++) {

                        /*
                         * Очередь имеет емкость 5 элементов.
                         *
                         * После заполнения буфера вызов put() блокируется до тех пор,
                         * пока consumer не освободит место через take().
                         *
                         * Благодаря этому producer автоматически замедляется и не может
                         * производить данные быстрее их обработки.
                         */
                        queue.put(i);

                        /*
                         * Использование ReentrantLock поддерживает количество одновременно
                         * действующих потоков пула ForkJoinPool, осуществляющих обработку
                         * виртуальных потоков.
                         *
                         * Метод PrintStream.println() содержит внутри synchronized-блок.
                         * Потоки, ожидающие монитор объекта PrintStream, переходят в состояние blocked,
                         * захватывая с собой поток ограниченного по количеству ядер пула.
                         *
                         * Ожидание же lock'а переводит поток в состояние waiting, на фоне чего
                         * исполняющий поток пула переключается на обработку другого виртуального потока,
                         * избегая простоя за ожиданием.
                         *
                         * В данной задаче разница незаметна из-за малого числа потоков,
                         * но при высокой конкуренции влияние может становиться существенным.
                         */
                        logLock.lock();
                        try {
                            System.out.println("Producer: put %s".formatted(i));
                        } finally {
                            logLock.unlock();
                        }
                    }

                /*
                 * Методы put(), take() и sleep() реагируют на запрос прерывания,
                 * выбрасывая InterruptedException.
                 *
                 * При этом interrupt-флаг автоматически сбрасывается обратно
                 * в состояние false, поэтому информация о факте прерывания теряется.
                 *
                 * Повторный вызов interrupt() восстанавливает флаг и позволяет
                 * коду выше по стеку определить, что поток получил запрос
                 * на завершение.
                 *
                 * Для данной задачи повторная проверка флага не требуется,
                 * но восстановление interrupt-статуса считается корректной
                 * практикой при обработке InterruptedException.
                 */
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                }
            });

            executor.submit(() -> {
                try {
                    for (int i = 1; i <= 10; i++) {

                        /*
                         * take() симметрична операции put():
                         * если очередь пуста, поток consumer будет ожидать
                         * появления нового элемента.
                         */
                        Integer item = queue.take();

                        logLock.lock();
                        try {
                            System.out.println("Consumer: take %s".formatted(item));
                        } finally {
                            logLock.unlock();
                        }

                        /*
                         * Искусственная задержка имитирует медленную обработку данных.
                         *
                         * Благодаря этому можно наблюдать работу backpressure:
                         * producer периодически вынужден ждать освобождения места
                         * в ограниченном буфере.
                         */
                        Thread.sleep(50);
                    }
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                }
            });

        }

        System.out.println("All producer and consumer tasks completed successfully.");
    }
}